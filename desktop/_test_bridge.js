const { chromium } = require('../prototype/node_modules/playwright-core');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/index.html', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1500);
  console.log('=== 桥接初始化 ===');
  console.log('模式:', await page.evaluate(() => window.__BRIDGE__?.mode));
  console.log('引擎在线:', await page.evaluate(() => window.__BRIDGE__?.online));
  console.log('状态栏:', await page.locator('.status').innerText());
  console.log('act 已包装:', await page.evaluate(() => window.act.toString().includes('async function')));
  console.log('=== 创建项目 → 引擎落库 ===');
  await page.fill('#idea', '测试：一个普通人的一生，从八岁到七十岁，三集竖屏短剧');
  await page.getByRole('button', { name: '开始创作' }).click();
  await page.waitForTimeout(600);
  const pid = await page.evaluate(() => window.__BRIDGE__?.projectId);
  console.log('projectId:', pid || 'NULL');
  console.log('视图:', await page.evaluate(() => document.querySelector('.view.on')?.id));
  console.log('=== 充值 → 后端账本 ===');
  const before = await page.locator('.balance b').innerText();
  await page.locator('.balance').click();
  await page.waitForTimeout(150);
  await page.locator('.plan', { hasText: '创作月包' }).click();
  await page.getByRole('button', { name: '确认支付' }).click();
  await page.waitForTimeout(600);
  console.log('余额:', before, '->', await page.locator('.balance b').innerText());
  console.log('=== 设置 → 引擎配置 ===');
  await page.locator('.seg button', { hasText: '设置' }).click();
  await page.waitForTimeout(150);
  await page.getByRole('button', { name: '测试连接' }).first().click();
  await page.waitForTimeout(500);
  console.log('测试反馈:', (await page.locator('#toast').innerText()).slice(0, 60));
  await page.getByRole('button', { name: '保存设置' }).click();
  await page.waitForTimeout(900);
  console.log('保存反馈:', (await page.locator('#toast').innerText()).slice(0, 60));
  console.log('=== 生成提交 ===');
  await page.locator('.seg button', { hasText: '制作' }).click();
  await page.waitForTimeout(150);
  await page.locator('.side .st').nth(4).click();
  await page.waitForTimeout(200);
  await page.getByRole('button', { name: '按这个方案生成' }).click();
  await page.waitForTimeout(700);
  console.log('生成反馈:', (await page.locator('#toast').innerText()).slice(0, 90));
  console.log('=== 导出 → 作品库 ===');
  await page.locator('.side .st').nth(7).click();
  await page.waitForTimeout(200);
  const exportBtn = page.getByRole('button', { name: '开始导出' });
  if (await exportBtn.count()) await exportBtn.click();
  await page.waitForTimeout(300);
  const goWorks = page.getByRole('button', { name: '去作品库' });
  if (await goWorks.count()) await goWorks.click();
  await page.waitForTimeout(1200);
  console.log('workId:', await page.evaluate(() => window.__BRIDGE__?.lastWork?.work_id || 'NULL'));
  console.log('作品库视图:', await page.evaluate(() => document.querySelector('.view.on')?.id));
  console.log('=== 错误 ===');
  console.log('pageerror:', errors.length ? errors : '无');
  await browser.close();
})();
