const { chromium } = require('../../prototype/node_modules/playwright-core');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await page.goto('http://127.0.0.1:8766/index.html', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1200);
  console.log('=== 首页 ===');
  console.log('标题:', await page.locator('.home-hero h1').innerText());
  console.log('项目卡:', await page.locator('.proj').count());
  console.log('状态:', await page.locator('.status').innerText());
  console.log('=== 创建项目（引擎落库）===');
  await page.fill('#idea, textarea', '测试：一个普通人的一生，从八岁到七十岁，三集竖屏短剧');
  await page.getByRole('button', { name: '开始创作' }).click();
  await page.waitForTimeout(700);
  console.log('路由:', new URL(page.url()).hash);
  console.log('第1步标题:', await page.locator('.card-hd').first().innerText());
  console.log('=== 8 步导航 ===');
  const steps = page.locator('.side .st');
  console.log('步骤数:', await steps.count());
  for (let i = 0; i < 8; i++) {
    await steps.nth(i).click();
    await page.waitForTimeout(100);
    const h = (await page.locator('.card-hd').first().innerText()).split('\n')[0];
    console.log(' ', i, h);
  }
  console.log('=== 角色多选 + 锁定弹窗 ===');
  await steps.nth(2).click(); await page.waitForTimeout(120);
  const before = await page.locator('.role.sel').count();
  await page.locator('.role').first().click(); await page.waitForTimeout(100);
  console.log('选中角色:', before, '->', await page.locator('.role.sel').count());
  await steps.nth(3).click(); await page.waitForTimeout(120);
  await page.getByRole('button', { name: '确认形象，开始拆镜头' }).click();
  await page.waitForTimeout(150);
  console.log('弹窗打开:', await page.locator('.ov.open').count() > 0);
  await page.getByRole('button', { name: '确认形象，继续' }).click();
  await page.waitForTimeout(150);
  console.log('锁定后步骤:', (await page.locator('.card-hd').first().innerText()).split('\n')[0]);
  console.log('=== 生成提交 ===');
  await page.getByRole('button', { name: '按这个方案生成' }).click();
  await page.waitForTimeout(700);
  console.log('生成步骤:', (await page.locator('.card-hd').first().innerText()).split('\n')[0]);
  await page.getByRole('button', { name: '跳过等待，直接完成' }).click(); await page.waitForTimeout(150);
  console.log('完成度:', await page.locator('.big-num').innerText());
  console.log('=== 导出 ===');
  await steps.nth(7).click(); await page.waitForTimeout(120);
  await page.getByRole('button', { name: '开始导出' }).click();
  await page.waitForTimeout(2600);
  console.log('导出状态:', await page.locator('.card-hd .pill').innerText());
  await page.getByRole('button', { name: '去作品库' }).click(); await page.waitForTimeout(300);
  console.log('作品库卡片:', await page.locator('.workcard').count(), '| hash:', new URL(page.url()).hash);
  console.log('=== 设置页 ===');
  await page.locator('.seg button', { hasText: '设置' }).click(); await page.waitForTimeout(200);
  console.log('设置分组:', await page.locator('.grp').count());
  await page.locator('.grp').first().locator('.ch').nth(1).click(); await page.waitForTimeout(100);
  console.log('密钥行出现:', await page.locator('.keyrow').count());
  await page.getByRole('button', { name: '保存设置' }).click(); await page.waitForTimeout(900);
  console.log('保存反馈:', (await page.locator('.toast').innerText()).slice(0, 50));
  console.log('=== 充值 ===');
  await page.locator('.balance').click(); await page.waitForTimeout(150);
  const beforeBal = await page.locator('.balance b').innerText();
  await page.locator('.plan', { hasText: '创作月包' }).click();
  await page.getByRole('button', { name: '确认支付' }).click(); await page.waitForTimeout(600);
  console.log('余额:', beforeBal, '->', await page.locator('.balance b').innerText());
  console.log('=== 主题切换 ===');
  await page.locator('.icobtn').click(); await page.waitForTimeout(150);
  console.log('主题:', await page.evaluate(() => document.documentElement.getAttribute('data-theme')));
  console.log('=== 错误 ===');
  console.log('pageerror:', errors.length ? errors.slice(0, 5) : '无');
  await page.screenshot({ path: '_vue_settings.png' });
  await browser.close();
})();
