const { chromium } = require('../prototype/node_modules/playwright-core');
const BASE = process.env.APP_URL || 'http://localhost:1420';
const PID = process.env.PROJECT_ID || '01M7W4FTKTFNFQKC71JVW6JTFZ';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror:' + e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`HTTP${r.status()} ${r.url().slice(0, 110)}`); });
  await page.goto(`${BASE}/#/p/${PID}`, { waitUntil: 'networkidle' });
  await page.waitForTimeout(1500);
  console.log('=== 第 3 步 · 定妆图 ===');
  await page.locator('.st').nth(2).click();
  await page.waitForTimeout(1200);
  const imgs = await page.locator('.rolegrid .role img').evaluateAll(els =>
    els.map(e => ({ w: e.naturalWidth, h: e.naturalHeight })));
  console.log(`图片 ${imgs.length} 张，全部渲染成功：${imgs.length > 0 && imgs.every(i => i.w > 0)}`);
  console.log('');
  console.log('=== 第 6 步 · 生成画面 ===');
  await page.locator('.st').nth(5).click();
  await page.waitForTimeout(900);
  const step6 = await page.locator('.card-bd').innerText().catch(() => '');
  console.log(step6.split('\n').filter(Boolean).slice(0, 8).join(' / '));
  console.log('');
  console.log('=== 第 7 步 · 看成片（真实生成的画面）===');
  await page.locator('.st').nth(6).click();
  await page.waitForTimeout(1500);
  const shot = await page.locator('.player img').evaluateAll(els =>
    els.map(e => ({ src: (e.getAttribute('src') || '').slice(0, 80), w: e.naturalWidth })));
  console.log('成片画面:', shot.length ? JSON.stringify(shot[0]) : '未找到图片');
  console.log('');
  console.log('=== 第 8 步 · 导出 ===');
  await page.locator('.st').nth(7).click();
  await page.waitForTimeout(1200);
  const step8 = await page.locator('.card-bd').innerText().catch(() => '');
  console.log(step8.split('\n').filter(Boolean).slice(0, 6).join(' / '));
  console.log('');
  console.log('页面错误:', errors.length ? errors.slice(0, 6) : '无');
  await browser.close();
})();
